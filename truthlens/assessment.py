"""Evidence summaries, separate from the unchanged forensic detectors and scoring.

This module classifies available evidence, not pixels as AI/camera ground truth.
It never changes findings, correlations, weights or the overall indicator.
"""
import re

LABELS = {
    "evidence_detected": "Evidence of AI generation detected",
    "possible": "Evidence suggests possible AI generation",
    "no_evidence": "No AI-generation evidence detected",
    "inconclusive": "Inconclusive",
    "not_assessed": "Not assessed",
}
LIMITATIONS = [
    "Absence of AI-generation evidence is not proof of camera capture.",
    "Metadata is an editable declaration; credentials describe signed claims, not independently verified creation.",
    "Experimental frequency cues can occur in ordinary resizing, compression, screenshots and graphics.",
    "No calibrated AI-image detection model is configured; no numerical confidence is reported.",
    "AI-generated content can be edited, and camera photographs can include AI-assisted edits; these are separate questions.",
]
# Deliberately specific declaration patterns. Generic 'generated', 'flux' and 'c2pa'
# are not sufficient generation declarations. Existing forensic rules are untouched.
DECLARATIONS = re.compile(
    r"\b(stable[ -]diffusion|midjourney|dall[ -]?[e·]e?|sdxl|comfyui|automatic1111|"
    r"ai[ -]generated|made with ai|generated by (?:an? )?(?:ai|firefly)|adobe firefly)\b", re.I)


def _result(status, evidence=None, methods=None, limitations=None):
    return {"status": status, "label": LABELS[status], "evidence": evidence or [],
            "methods": methods or [], "confidence": None, "confidence_calibrated": False,
            "model_status": "not_configured", "limitations": limitations or list(LIMITATIONS)}


def assess_image(result):
    evidence = []
    meta = result.get("metadata") or {}
    c2 = (result.get("provenance") or {}).get("c2pa") or {}
    findings = result.get("findings") or []
    failed = any(str(x).startswith("Analysis failed:") for x in result.get("limitations", []))
    methods = [
        {"name": "Metadata declarations", "status": "inspected" if meta else "unavailable"},
        {"name": "C2PA generation declarations", "status": c2.get("status", "not_checked")},
        {"name": "Experimental frequency analysis", "status": "performed" if result.get("generator") else "not_performed"},
        {"name": "Trained AI-image detector", "status": "not_configured"},
    ]
    fields = {f"EXIF.{k}": v for k, v in meta.get("exif", {}).items()
              if k in ("Software", "ImageDescription", "Artist", "UserComment")}
    fields.update({f"text.{k}": v for k, v in meta.get("text_chunks", {}).items()})
    for field, value in fields.items():
        hit = DECLARATIONS.search(str(value))
        if hit:
            evidence.append({"method": "metadata_declaration", "field": field,
                             "detail": f"Metadata contains '{hit.group(0)}'. This is an editable declaration, not verified origin.",
                             "refs": [f["id"] for f in findings if f.get("category") == "synthetic-generation" and not f.get("experimental")]})
    intact_declaration = bool(c2.get("ai_generated") and c2.get("status") in ("valid", "valid_untrusted"))
    if c2.get("ai_generated"):
        evidence.append({"method": "c2pa_declaration", "credential_status": c2.get("status"),
                         "detail": "Credentials declare AI-generated or AI-assisted content. " +
                                   ("The declaration's signature/content binding is intact; issuer trust is separate." if intact_declaration else
                                    "The declaration is not backed by validated intact credentials."),
                         "refs": [f["id"] for f in findings if f.get("category") == "c2pa"]})
    for finding in findings:
        if finding.get("experimental") and finding.get("category") == "synthetic-generation":
            evidence.append({"method": "experimental_frequency", "detail": finding["explanation"], "refs": [finding["id"]]})
    if intact_declaration:
        status = "evidence_detected"
    elif evidence:
        status = "possible"
    elif failed or not (meta.get("exif") or meta.get("text_chunks") or c2.get("status") in ("valid", "valid_untrusted")):
        status = "inconclusive"
    else:
        status = "no_evidence"
    limits = list(LIMITATIONS)
    if failed:
        limits.insert(0, "Image analysis failed or is incomplete; missing results are not negative evidence.")
    if not evidence:
        limits.insert(0, "No positive generation evidence was found in the available checks; content origin remains unknown.")
    return _result(status, evidence, methods, limits)


def build_assessments(evidence, results, overall):
    images = [e for e in evidence if e["modality"] == "image" and e.get("role") != "reference"]
    items, provenance = [], []
    for image in images:
        result = results.get(image["id"], {})
        items.append({"evidence_id": image["id"], "filename": image["filename"], **assess_image(result)})
        pv = result.get("provenance") or {}
        c2 = pv.get("c2pa") or {}
        provenance.append({"evidence_id": image["id"], "c2pa_status": c2.get("status", "not_checked"),
                           "declared_signer": c2.get("signer"), "declared_device": (result.get("metadata") or {}).get("device"),
                           "declared_ai_generation": c2.get("ai_generated"),
                           "registry_match": bool((pv.get("registry") or {}).get("exact")),
                           "issuer_trust": "not_established", "independently_verified_origin": "not_established",
                           "note": "Credential validation, declared origin and independently verified origin are distinct. No independent origin trust policy is configured."})
    statuses = {item["status"] for item in items}
    status = next((s for s in ("evidence_detected", "possible", "inconclusive", "no_evidence") if s in statuses), "not_assessed")
    ai = _result(status)
    ai["items"] = items
    ai["evidence"] = [{"evidence_id": item["evidence_id"], **entry} for item in items for entry in item["evidence"]]
    ai["methods"] = [{"evidence_id": item["evidence_id"], **method} for item in items for method in item["methods"]]
    if not images:
        ai["limitations"].insert(0, "No still-image evidence was supplied; video-frame AI generation is not assessed.")
    return {
        "manipulation": {"indicator": overall["score"], "label": overall["label"],
                         "scope": "Existing forensic indicator preserved, including its legacy metadata/provenance correlations. It is not an AI-generation probability or proof of camera capture."},
        "ai_generation": ai,
        "content_provenance": {"items": provenance, "independently_verified_origin": "not_established"},
        "sync_id": {"status": "not_assessed", "detail": "Use the explicit Sync ID tool to compare SHA-256 and verify Ed25519 signatures. Issuer trust and origin are reported separately."},
    }
